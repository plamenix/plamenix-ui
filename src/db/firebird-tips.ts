/**
 * Static catalog of Firebird-specific tips rotated on the welcome
 * dashboard. Curated rather than crowdsourced — each line earns its
 * spot by surfacing a non-obvious behaviour, a syntax that newcomers
 * miss, or a sharp edge that bites in production.
 *
 * Adding a tip:
 * - Pick a stable `id` (kebab-case noun phrase). Used as the React key
 *   and as the rotation cursor; never reuse a retired id.
 * - Keep `text` short — a line that fits on one row of the card at
 *   the typical viewport. Two short sentences max.
 * - Set `minVersion` to the integer Firebird major where the feature
 *   first appeared. Omit when the tip applies universally (FB 2.5+).
 * - Add `link` only when the relevant chapter of the Firebird docs is
 *   genuinely useful as a follow-up.
 */

export interface FirebirdTip {
  id: string;
  text: string;
  /** Lowest Firebird major version where the tip applies. Tips with
   *  a higher floor than the active engine are filtered out. */
  minVersion?: number;
  /** Optional documentation URL surfaced as a small "learn more" anchor
   *  next to the tip text. */
  link?: string;
}

