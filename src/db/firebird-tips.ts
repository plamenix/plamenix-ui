/** Returns the tips that apply to the given engine major version. A
 *  `null` version (no live connection yet) keeps everything. Stable
 *  order — the rotation cursor relies on this. */
export function filterTipsForVersion(version: number | null): FirebirdTip[] {
  if (version === null) return FIREBIRD_TIPS.slice();
  return FIREBIRD_TIPS.filter((tip) => (tip.minVersion ?? 0) <= version);
}

/** Pulls the engine major out of a free-form `engineVersion` string
 *  (e.g. `"WI-V5.0.1.1469 Firebird 5.0"`). Returns `null` on any
 *  parse miss — the caller treats `null` as "no version filter". */
export function parseEngineMajor(engineVersion: string | null | undefined): number | null {
  if (!engineVersion) return null;
  // The string usually contains "Firebird X.Y" near the end; fall back
  // to a generic digit-pair scan so format drift across versions
  // doesn't accidentally hide every tip.
  const direct = /Firebird\s+(\d+)/i.exec(engineVersion);
  if (direct && direct[1]) return Number(direct[1]);
  const generic = /\b([3-9])\.\d+/.exec(engineVersion);
  if (generic && generic[1]) return Number(generic[1]);
  return null;
}
